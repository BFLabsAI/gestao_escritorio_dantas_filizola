CREATE POLICY "Allow anon select meta adsets" ON relatorio_meta_dim_adsets FOR SELECT TO anon USING (true);

CREATE POLICY "Allow anon insert meta ads" ON relatorio_meta_dim_ads FOR INSERT TO anon WITH CHECK (true);
CREATE POLICY "Allow anon select meta ads" ON relatorio_meta_dim_ads FOR SELECT TO anon USING (true);

CREATE POLICY "Allow anon insert meta facts" ON relatorio_meta_fact_performance FOR INSERT TO anon WITH CHECK (true);
CREATE POLICY "Allow anon select meta facts" ON relatorio_meta_fact_performance FOR SELECT TO anon USING (true);

